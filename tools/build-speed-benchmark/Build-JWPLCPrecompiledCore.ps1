[CmdletBinding()]
param(
    [string]$ArduinoCli = "arduino-cli",
    [ValidateSet("Basic", "Core")]
    [string[]]$Targets = @("Basic"),
    [string]$Sketch = "01_empty",
    [int]$Jobs = 0,
    [string]$OutputRoot = ""
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = "Stop"

$ScriptRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$RepoRoot = [System.IO.Path]::GetFullPath((Join-Path $ScriptRoot "..\.."))
$PlatformRoot = Join-Path $RepoRoot "JWPLC\2.1.0"
$SketchRoot = Join-Path $ScriptRoot "sketches"
$BoardsLocalPath = Join-Path $PlatformRoot "boards.local.txt"
$P2CorePath = Join-Path $PlatformRoot "cores\jwcontrol_precompiled_stub\precompiled_core_stub.c"

if ([string]::IsNullOrWhiteSpace($OutputRoot))
{
    $OutputRoot = Join-Path $ScriptRoot "p2-work"
}

function Invoke-NativeCaptured
{
    param(
        [Parameter(Mandatory = $true)][string]$FilePath,
        [Parameter(Mandatory = $true)][string[]]$Arguments
    )

    $previousPreference = $ErrorActionPreference
    $nativeOutput = @()
    $exitCode = -1

    try
    {
        $ErrorActionPreference = "Continue"
        $nativeOutput = @(& $FilePath @Arguments 2>&1 | ForEach-Object { $_.ToString() })
        $exitCode = $LASTEXITCODE
    }
    finally
    {
        $ErrorActionPreference = $previousPreference
    }

    return [PSCustomObject]@{
        ExitCode = [int]$exitCode
        Output   = $nativeOutput
    }
}

function Get-TargetInfo
{
    param([string]$Target)

    switch ($Target)
    {
        "Basic" {
            return [PSCustomObject]@{
                Target     = "Basic"
                BoardKey   = "jwplcbasic"
                Fqbn       = "jwplc_local:esp32:jwplcbasic"
                BuildBoard = "JWPLCBASIC"
            }
        }
        "Core" {
            return [PSCustomObject]@{
                Target     = "Core"
                BoardKey   = "jwplcbasiccore"
                Fqbn       = "jwplc_local:esp32:jwplcbasiccore"
                BuildBoard = "JWPLCBASICCORE"
            }
        }
        default { throw "Target no soportado: $Target" }
    }
}

function Remove-P2Block
{
    param([string]$Text)

    if ([string]::IsNullOrEmpty($Text))
    {
        return ""
    }

    $pattern = '(?ms)^# BEGIN JWPLC_P2_PRECOMPILED_CORE\r?\n.*?^# END JWPLC_P2_PRECOMPILED_CORE\r?\n?'
    return [regex]::Replace($Text, $pattern, "").TrimEnd()
}

function Set-P2Overrides
{
    param([object[]]$TargetInfos)

    $existing = ""
    if (Test-Path $BoardsLocalPath)
    {
        $existing = Get-Content -Path $BoardsLocalPath -Raw
    }

    $baseText = Remove-P2Block -Text $existing

    if ($TargetInfos.Count -eq 0)
    {
        if ([string]::IsNullOrWhiteSpace($baseText))
        {
            if (Test-Path $BoardsLocalPath)
            {
                Remove-Item -Path $BoardsLocalPath -Force
            }
        }
        else
        {
            ($baseText + [Environment]::NewLine) | Out-File -FilePath $BoardsLocalPath -Encoding ascii
        }
        return
    }

    $lines = New-Object System.Collections.Generic.List[string]
    if (-not [string]::IsNullOrWhiteSpace($baseText))
    {
        $lines.Add($baseText)
        $lines.Add("")
    }

    $lines.Add("# BEGIN JWPLC_P2_PRECOMPILED_CORE")
    $lines.Add("# Generated by Build-JWPLCPrecompiledCore.ps1. Do not commit during pilot.")
    foreach ($info in $TargetInfos)
    {
        $lines.Add(("{0}.build.core=jwcontrol_precompiled_stub" -f $info.BoardKey))
    }
    $lines.Add("# END JWPLC_P2_PRECOMPILED_CORE")
    $lines | Out-File -FilePath $BoardsLocalPath -Encoding ascii
}

function Invoke-ArduinoCompile
{
    param(
        [object]$TargetInfo,
        [string]$BuildPath,
        [string]$LogPath,
        [string]$SketchPath
    )

    if (Test-Path $BuildPath)
    {
        Remove-Item -Path $BuildPath -Recurse -Force
    }
    New-Item -ItemType Directory -Path $BuildPath -Force | Out-Null

    $args = @(
        "compile",
        "-b", $TargetInfo.Fqbn,
        "-j", $Jobs.ToString(),
        "-v",
        "--build-path", $BuildPath,
        "--clean",
        $SketchPath
    )

    Write-Host ""
    Write-Host ("arduino-cli {0}" -f ($args -join " ")) -ForegroundColor DarkGray

    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    $native = Invoke-NativeCaptured -FilePath $ArduinoCli -Arguments $args
    $sw.Stop()

    @($native.Output) | Out-File -FilePath $LogPath -Encoding utf8

    if ($native.ExitCode -ne 0)
    {
        Write-Host ("Compilacion fallo (exit={0})." -f $native.ExitCode) -ForegroundColor Red
        @($native.Output | Select-Object -Last 15) | ForEach-Object { Write-Host $_ -ForegroundColor DarkYellow }
        throw "Arduino CLI fallo. Revisar: $LogPath"
    }

    $allCompiles = @(
        $native.Output | Where-Object { ([string]$_) -match '-MMD\s+-c\s' }
    ).Count

    $sourceCoreCompiles = @(
        $native.Output | Where-Object {
            $line = [string]$_
            ($line -match '-MMD\s+-c\s') -and ($line -match '[\\/]cores[\\/]jwcontrol[\\/]')
        }
    ).Count

    $stubCoreCompiles = @(
        $native.Output | Where-Object {
            $line = [string]$_
            ($line -match '-MMD\s+-c\s') -and ($line -match 'p2_core_stub\.c')
        }
    ).Count

    Write-Host ("Compilacion OK en {0:N3} s | total={1} | core fuente={2} | stub={3}" -f $sw.Elapsed.TotalSeconds, $allCompiles, $sourceCoreCompiles, $stubCoreCompiles) -ForegroundColor Green

    return [PSCustomObject]@{
        DurationMs         = [Math]::Round($sw.Elapsed.TotalMilliseconds, 3)
        Output             = @($native.Output)
        AllCompiles        = $allCompiles
        SourceCoreCompiles = $sourceCoreCompiles
        StubCoreCompiles   = $stubCoreCompiles
        BuildPath          = $BuildPath
        LogPath            = $LogPath
    }
}

function Get-AppBinInfo
{
    param([string]$BuildPath)

    $bin = Get-ChildItem -Path $BuildPath -Filter "*.ino.bin" -File | Select-Object -First 1
    if ($null -eq $bin)
    {
        throw "No se encontro app .ino.bin en $BuildPath"
    }

    return [PSCustomObject]@{
        Path   = $bin.FullName
        Bytes  = [int64]$bin.Length
        SHA256 = (Get-FileHash -Path $bin.FullName -Algorithm SHA256).Hash.ToLowerInvariant()
    }
}

if ($Jobs -lt 0)
{
    throw "Jobs debe ser 0 o mayor."
}

if ($null -eq (Get-Command $ArduinoCli -ErrorAction SilentlyContinue))
{
    throw "No se encontro '$ArduinoCli' en PATH."
}

if (-not (Test-Path $P2CorePath))
{
    throw "No existe el core stub P2. Ejecuta git pull antes de P2: $P2CorePath"
}

$sketchPath = Join-Path $SketchRoot $Sketch
if (-not (Test-Path $sketchPath))
{
    throw "Sketch no encontrado: $sketchPath"
}

$targetInfos = @($Targets | ForEach-Object { Get-TargetInfo -Target $_ })
$runId = (Get-Date).ToString("yyyyMMdd_HHmmss")
$runRoot = Join-Path $OutputRoot $runId
$summaryPath = Join-Path $runRoot "P2_SUMMARY.md"
New-Item -ItemType Directory -Path $runRoot -Force | Out-Null

Write-Host "P2 - Core JWPLC precompilado por perfil" -ForegroundColor Cyan
Write-Host ("Targets: {0}" -f ($Targets -join ", "))
Write-Host ("Sketch: {0}" -f $Sketch)
Write-Host ""
Write-Host "P2 primero desactiva el overlay, genera core.a desde fuentes, y solo luego activa el core stub." -ForegroundColor DarkGray

# Always start from the normal source core.
Set-P2Overrides -TargetInfos @()

$sourceRows = @()
$verifyRows = @()
$p2Activated = $false

try
{
    foreach ($info in $targetInfos)
    {
        $archiveDir = Join-Path $PlatformRoot ("precompiled\core\{0}" -f $info.BuildBoard)
        $archivePath = Join-Path $archiveDir "core.a"
        if (Test-Path $archivePath)
        {
            Remove-Item -Path $archivePath -Force
        }

        $sourceBuild = Join-Path $runRoot ("source-{0}" -f $info.Target)
        $sourceLog = Join-Path $runRoot ("source-{0}.log" -f $info.Target)

        Write-Host ("[1] {0}: build fuente limpio..." -f $info.Target) -ForegroundColor Cyan
        $sourceResult = Invoke-ArduinoCompile -TargetInfo $info -BuildPath $sourceBuild -LogPath $sourceLog -SketchPath $sketchPath

        if ($sourceResult.SourceCoreCompiles -lt 50)
        {
            throw ("El build fuente de {0} no parece haber compilado el core completo: {1} unidades." -f $info.Target, $sourceResult.SourceCoreCompiles)
        }

        $builtCore = Join-Path $sourceBuild "core\core.a"
        if (-not (Test-Path $builtCore))
        {
            throw "No se genero core.a fuente: $builtCore"
        }

        New-Item -ItemType Directory -Path $archiveDir -Force | Out-Null
        Copy-Item -Path $builtCore -Destination $archivePath -Force

        $app = Get-AppBinInfo -BuildPath $sourceBuild
        $archiveFile = Get-Item $archivePath
        $archiveHash = (Get-FileHash -Path $archivePath -Algorithm SHA256).Hash.ToLowerInvariant()

        $sourceRows += [PSCustomObject]@{
            Target       = $info.Target
            BuildBoard   = $info.BuildBoard
            DurationMs   = $sourceResult.DurationMs
            Compiles     = $sourceResult.AllCompiles
            CoreCompiles = $sourceResult.SourceCoreCompiles
            ArchivePath  = $archivePath
            ArchiveBytes = [int64]$archiveFile.Length
            ArchiveSHA   = $archiveHash
            AppBytes     = $app.Bytes
            AppSHA       = $app.SHA256
            BuildPath    = $sourceBuild
        }

        Write-Host ("Core archivado: {0} ({1} bytes)" -f $archivePath, $archiveFile.Length) -ForegroundColor Green
    }

    Write-Host ""
    Write-Host "Activando overlay P2 en boards.local.txt..." -ForegroundColor Cyan
    Set-P2Overrides -TargetInfos $targetInfos
    $p2Activated = $true

    foreach ($info in $targetInfos)
    {
        $verifyBuild = Join-Path $runRoot ("verify-{0}" -f $info.Target)
        $verifyLog = Join-Path $runRoot ("verify-{0}.log" -f $info.Target)

        Write-Host ("[2] {0}: build limpio con core precompilado..." -f $info.Target) -ForegroundColor Cyan
        $verifyResult = Invoke-ArduinoCompile -TargetInfo $info -BuildPath $verifyBuild -LogPath $verifyLog -SketchPath $sketchPath

        if ($verifyResult.SourceCoreCompiles -ne 0)
        {
            throw ("P2 fallo: {0} todavia compilo {1} unidades del core fuente." -f $info.Target, $verifyResult.SourceCoreCompiles)
        }

        if ($verifyResult.StubCoreCompiles -ne 1)
        {
            throw ("P2 esperaba 1 compilacion del stub en {0}, obtuvo {1}." -f $info.Target, $verifyResult.StubCoreCompiles)
        }

        $sourceRow = $sourceRows | Where-Object { $_.Target -eq $info.Target } | Select-Object -First 1
        $app = Get-AppBinInfo -BuildPath $verifyBuild

        $verifyRows += [PSCustomObject]@{
            Target      = $info.Target
            DurationMs  = $verifyResult.DurationMs
            Compiles    = $verifyResult.AllCompiles
            StubCompiles = $verifyResult.StubCoreCompiles
            AppBytes    = $app.Bytes
            AppSHA      = $app.SHA256
            SameBytes   = ($app.Bytes -eq $sourceRow.AppBytes)
            SameSHA     = ($app.SHA256 -eq $sourceRow.AppSHA)
            BuildPath   = $verifyBuild
        }
    }
}
catch
{
    if ($p2Activated)
    {
        Write-Host "P2 fallo; restaurando build.core fuente automaticamente..." -ForegroundColor Yellow
        Set-P2Overrides -TargetInfos @()
    }
    throw
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# P2 - core JWPLC precompilado por perfil")
$lines.Add("")
$lines.Add(("Run: {0}" -f $runId))
$lines.Add("")
$lines.Add("| Target | Fuente s | P2 s | Compiles fuente | Compiles P2 | Core fuente | Stub P2 | App bytes igual | App SHA igual |")
$lines.Add("|---|---:|---:|---:|---:|---:|---:|---|---|")
foreach ($sourceRow in $sourceRows)
{
    $verifyRow = $verifyRows | Where-Object { $_.Target -eq $sourceRow.Target } | Select-Object -First 1
    $lines.Add(("| {0} | {1:N3} | {2:N3} | {3} | {4} | {5} | {6} | {7} | {8} |" -f `
        $sourceRow.Target,
        ($sourceRow.DurationMs / 1000.0),
        ($verifyRow.DurationMs / 1000.0),
        $sourceRow.Compiles,
        $verifyRow.Compiles,
        $sourceRow.CoreCompiles,
        $verifyRow.StubCompiles,
        $verifyRow.SameBytes,
        $verifyRow.SameSHA))
}
$lines.Add("")
$lines.Add("P2 activo: boards.local.txt cambia solamente los targets seleccionados a build.core=jwcontrol_precompiled_stub.")
$lines.Add("Los core.a generados quedan sin commit en JWPLC/2.1.0/precompiled/core/<BUILD_BOARD>/core.a.")
$lines.Add("Rollback: ejecutar Remove-JWPLCPrecompiledCore.ps1.")
$lines | Out-File -FilePath $summaryPath -Encoding ascii

Write-Host ""
Write-Host "P2 generado y verificado correctamente." -ForegroundColor Green
foreach ($sourceRow in $sourceRows)
{
    $verifyRow = $verifyRows | Where-Object { $_.Target -eq $sourceRow.Target } | Select-Object -First 1
    $sourceSeconds = $sourceRow.DurationMs / 1000.0
    $verifySeconds = $verifyRow.DurationMs / 1000.0
    $gain = if ($sourceSeconds -gt 0) { 100.0 * ($sourceSeconds - $verifySeconds) / $sourceSeconds } else { 0.0 }
    Write-Host ("  {0}: {1:N3} s -> {2:N3} s ({3:N1}% menos), compiles {4} -> {5}" -f $sourceRow.Target, $sourceSeconds, $verifySeconds, $gain, $sourceRow.Compiles, $verifyRow.Compiles) -ForegroundColor Green
    Write-Host ("       app bytes iguales={0}, SHA igual={1}" -f $verifyRow.SameBytes, $verifyRow.SameSHA) -ForegroundColor DarkGray
}
Write-Host ("Resumen: {0}" -f $summaryPath)
Write-Host ""
Write-Host "IMPORTANTE: no hacer git add de boards.local.txt, precompiled/core ni p2-work durante el piloto." -ForegroundColor Yellow
