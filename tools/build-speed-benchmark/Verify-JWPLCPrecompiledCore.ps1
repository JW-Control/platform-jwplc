[CmdletBinding()]
param(
    [ValidateSet("Basic", "Core")]
    [string]$Target = "Basic",
    [string]$ArduinoCli = "arduino-cli",
    [int]$Jobs = 0,
    [string]$ReferenceRunPath = ""
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = "Stop"

$ScriptRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$RepoRoot = [System.IO.Path]::GetFullPath((Join-Path $ScriptRoot "..\.."))
$PlatformRoot = Join-Path $RepoRoot "JWPLC\2.1.0"
$BoardsLocalPath = Join-Path $PlatformRoot "boards.local.txt"
$SketchPath = Join-Path $ScriptRoot "sketches\01_empty"
$VerifyRoot = Join-Path $ScriptRoot "p2-verify-work"

function Get-TargetInfo
{
    param([string]$Name)

    switch ($Name)
    {
        "Basic" {
            return [PSCustomObject]@{
                Target = "Basic"
                BoardKey = "jwplcbasic"
                Fqbn = "jwplc_local:esp32:jwplcbasic"
                BuildBoard = "JWPLCBASIC"
            }
        }
        "Core" {
            return [PSCustomObject]@{
                Target = "Core"
                BoardKey = "jwplcbasiccore"
                Fqbn = "jwplc_local:esp32:jwplcbasiccore"
                BuildBoard = "JWPLCBASICCORE"
            }
        }
    }
}

function Remove-P2Block
{
    param([string]$Text)

    if ([string]::IsNullOrEmpty($Text)) { return "" }
    $pattern = '(?ms)^# BEGIN JWPLC_P2_PRECOMPILED_CORE\r?\n.*?^# END JWPLC_P2_PRECOMPILED_CORE\r?\n?'
    return [regex]::Replace($Text, $pattern, "").TrimEnd()
}

function Set-P2Override
{
    param([object]$Info, [bool]$Enabled)

    $existing = ""
    if (Test-Path $BoardsLocalPath)
    {
        $existing = Get-Content -Path $BoardsLocalPath -Raw
    }

    $baseText = Remove-P2Block -Text $existing
    if (-not $Enabled)
    {
        if ([string]::IsNullOrWhiteSpace($baseText))
        {
            if (Test-Path $BoardsLocalPath) { Remove-Item $BoardsLocalPath -Force }
        }
        else
        {
            ($baseText + [Environment]::NewLine) | Out-File $BoardsLocalPath -Encoding ascii
        }
        return
    }

    $lines = New-Object System.Collections.Generic.List[string]
    if (-not [string]::IsNullOrWhiteSpace($baseText))
    {
        $lines.Add($baseText)
        $lines.Add("")
    }
    $lines.Add("# BEGIN JWPLC_P2_PRECOMPILED_CORE")
    $lines.Add("# Generated by Verify-JWPLCPrecompiledCore.ps1. Do not commit during pilot.")
    $lines.Add(("{0}.build.core=jwcontrol_p2" -f $Info.BoardKey))
    $lines.Add("# END JWPLC_P2_PRECOMPILED_CORE")
    $lines | Out-File $BoardsLocalPath -Encoding ascii
}

function Invoke-NativeCaptured
{
    param([string]$FilePath, [string[]]$Arguments)

    $previousPreference = $ErrorActionPreference
    $output = @()
    $exitCode = -1
    try
    {
        $ErrorActionPreference = "Continue"
        $output = @(& $FilePath @Arguments 2>&1 | ForEach-Object { $_.ToString() })
        $exitCode = $LASTEXITCODE
    }
    finally
    {
        $ErrorActionPreference = $previousPreference
    }

    return [PSCustomObject]@{ ExitCode = [int]$exitCode; Output = $output }
}

function Get-AppBin
{
    param([string]$BuildPath)
    $bin = Get-ChildItem $BuildPath -Filter "*.ino.bin" -File | Select-Object -First 1
    if ($null -eq $bin) { throw "No se encontro app .ino.bin en $BuildPath" }
    return $bin
}

function Test-PayloadEquivalent
{
    param([string]$ReferencePath, [string]$CandidatePath)

    $a = [System.IO.File]::ReadAllBytes($ReferencePath)
    $b = [System.IO.File]::ReadAllBytes($CandidatePath)
    if ($a.Length -ne $b.Length) { return $false }
    if ($a.Length -lt 256) { return $false }

    # ESP32 recipe writes the ELF SHA-256 at offset 0xB0. The final image
    # checksum/digest also changes when that metadata changes. For this P2
    # diagnostic, compare every other byte of the application image.
    $elfHashStart = 0xB0
    $elfHashEnd = 0xCF
    $tailStart = $a.Length - 33

    for ($i = 0; $i -lt $a.Length; $i++)
    {
        if (($i -ge $elfHashStart -and $i -le $elfHashEnd) -or ($i -ge $tailStart))
        {
            continue
        }
        if ($a[$i] -ne $b[$i]) { return $false }
    }
    return $true
}

function Find-LatestReferenceBuild
{
    param([string]$Name)

    $root = Join-Path $ScriptRoot "p2-work"
    if (-not (Test-Path $root)) { return "" }

    foreach ($dir in @(Get-ChildItem $root -Directory | Sort-Object LastWriteTime -Descending))
    {
        $candidate = Join-Path $dir.FullName ("source-{0}" -f $Name)
        if (Test-Path $candidate)
        {
            $bin = Get-ChildItem $candidate -Filter "*.ino.bin" -File -ErrorAction SilentlyContinue | Select-Object -First 1
            if ($null -ne $bin) { return $candidate }
        }
    }
    return ""
}

if ($Jobs -lt 0) { throw "Jobs debe ser 0 o mayor." }
if ($null -eq (Get-Command $ArduinoCli -ErrorAction SilentlyContinue)) { throw "No se encontro arduino-cli." }

$info = Get-TargetInfo -Name $Target
$archivePath = Join-Path $PlatformRoot ("precompiled\core\{0}\core.a" -f $info.BuildBoard)
if (-not (Test-Path $archivePath))
{
    throw "No existe core P2 precompilado: $archivePath"
}

if ([string]::IsNullOrWhiteSpace($ReferenceRunPath))
{
    $ReferenceRunPath = Find-LatestReferenceBuild -Name $Target
}
if ([string]::IsNullOrWhiteSpace($ReferenceRunPath) -or -not (Test-Path $ReferenceRunPath))
{
    throw "No se encontro source build de referencia. Usa -ReferenceRunPath."
}

$referenceBin = Get-AppBin -BuildPath $ReferenceRunPath
$runId = (Get-Date).ToString("yyyyMMdd_HHmmss")
$runRoot = Join-Path $VerifyRoot $runId
$buildPath = Join-Path $runRoot ("verify-{0}" -f $Target)
$logPath = Join-Path $runRoot ("verify-{0}.log" -f $Target)
$summaryPath = Join-Path $runRoot "P2_VERIFY_SUMMARY.md"
New-Item -ItemType Directory -Path $buildPath -Force | Out-Null

Write-Host "P2 - verificacion de core precompilado existente" -ForegroundColor Cyan
Write-Host ("Target: {0}" -f $Target)
Write-Host ("Archive: {0}" -f $archivePath)
Write-Host ("Referencia: {0}" -f $referenceBin.FullName)

Set-P2Override -Info $info -Enabled $true
$keepEnabled = $false

try
{
    $args = @("compile", "-b", $info.Fqbn, "-j", $Jobs.ToString(), "-v", "--build-path", $buildPath, "--clean", $SketchPath)
    Write-Host ""
    Write-Host ("arduino-cli {0}" -f ($args -join " ")) -ForegroundColor DarkGray

    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    $native = Invoke-NativeCaptured -FilePath $ArduinoCli -Arguments $args
    $sw.Stop()
    @($native.Output) | Out-File $logPath -Encoding utf8

    if ($native.ExitCode -ne 0)
    {
        throw "Arduino CLI fallo. Revisar: $logPath"
    }

    $compileLines = @($native.Output | Where-Object { ([string]$_) -match '-MMD\s+-c\s' })
    $allCompiles = $compileLines.Count

    # Match only the actual source operand immediately before -o. Do not count
    # -I.../cores/jwcontrol include paths present in every compile command.
    $sourcePattern = '"[^"]*[\\/]+cores[\\/]+jwcontrol[\\/]+[^"]+"\s+-o\s+"'
    $stubPattern = '"[^"]*[\\/]+cores[\\/]+jwcontrol_p2[\\/]+p2_core_stub\.c"\s+-o\s+"'
    $sourceCoreCompiles = @($compileLines | Where-Object { ([string]$_) -match $sourcePattern }).Count
    $stubCompiles = @($compileLines | Where-Object { ([string]$_) -match $stubPattern }).Count
    $preprocessPasses = @($native.Output | Where-Object { ([string]$_) -match 'xtensa-esp32-elf-g\+\+.*\s-E\s' }).Count

    $candidateBin = Get-AppBin -BuildPath $buildPath
    $sameBytes = ($candidateBin.Length -eq $referenceBin.Length)
    $sameRawSHA = ((Get-FileHash $candidateBin.FullName -Algorithm SHA256).Hash -eq (Get-FileHash $referenceBin.FullName -Algorithm SHA256).Hash)
    $samePayload = Test-PayloadEquivalent -ReferencePath $referenceBin.FullName -CandidatePath $candidateBin.FullName

    Write-Host ""
    Write-Host ("Tiempo: {0:N3} s" -f $sw.Elapsed.TotalSeconds) -ForegroundColor Green
    Write-Host ("Compilaciones: total={0}, core fuente={1}, stub={2}" -f $allCompiles, $sourceCoreCompiles, $stubCompiles) -ForegroundColor Green
    Write-Host ("Preprocesados -E: {0}" -f $preprocessPasses) -ForegroundColor DarkGray
    Write-Host ("App bytes iguales={0}, SHA raw igual={1}, payload igual={2}" -f $sameBytes, $sameRawSHA, $samePayload) -ForegroundColor DarkGray

    if ($sourceCoreCompiles -ne 0) { throw "P2 todavia compilo fuentes de jwcontrol." }
    if ($stubCompiles -ne 1) { throw ("P2 esperaba 1 stub, obtuvo {0}." -f $stubCompiles) }
    if (-not $sameBytes) { throw "P2 cambio el tamano de la app." }
    if (-not $samePayload) { throw "P2 cambio bytes de payload fuera de metadatos/hash." }

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("# P2 verify")
    $lines.Add("")
    $lines.Add(("Target: {0}" -f $Target))
    $lines.Add(("Tiempo: {0:N3} s" -f $sw.Elapsed.TotalSeconds))
    $lines.Add(("Compiles total: {0}" -f $allCompiles))
    $lines.Add(("Core fuente: {0}" -f $sourceCoreCompiles))
    $lines.Add(("Stub: {0}" -f $stubCompiles))
    $lines.Add(("Preprocesados -E: {0}" -f $preprocessPasses))
    $lines.Add(("App bytes iguales: {0}" -f $sameBytes))
    $lines.Add(("SHA raw igual: {0}" -f $sameRawSHA))
    $lines.Add(("Payload fuera de hashes igual: {0}" -f $samePayload))
    $lines | Out-File $summaryPath -Encoding ascii

    $keepEnabled = $true
    Write-Host ""
    Write-Host "P2 verificado correctamente. Overlay queda ACTIVO para el siguiente benchmark." -ForegroundColor Green
    Write-Host ("Resumen: {0}" -f $summaryPath)
}
finally
{
    if (-not $keepEnabled)
    {
        Write-Host "Restaurando build.core fuente por fallo de verificacion..." -ForegroundColor Yellow
        Set-P2Override -Info $info -Enabled $false
    }
}
