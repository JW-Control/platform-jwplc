[CmdletBinding()]
param()

Set-StrictMode -Version 2.0
$ErrorActionPreference = "Stop"

$ScriptRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$RepoRoot = [System.IO.Path]::GetFullPath((Join-Path $ScriptRoot "..\.."))
$PlatformRoot = Join-Path $RepoRoot "JWPLC\2.1.0"
$BoardsLocalPath = Join-Path $PlatformRoot "boards.local.txt"
$PlatformLocalPath = Join-Path $PlatformRoot "platform.local.txt"
$ArchivePath = Join-Path $PlatformRoot "precompiled\core\JWPLCBASIC\core.a"
$StubPath = Join-Path $PlatformRoot "cores\jwcontrol_precompiled_stub\precompiled_core_stub.c"

function Remove-P2Block
{
    param([string]$Text)

    if ([string]::IsNullOrEmpty($Text)) { return "" }
    $pattern = '(?ms)^# BEGIN JWPLC_P2_PRECOMPILED_CORE\r?\n.*?^# END JWPLC_P2_PRECOMPILED_CORE\r?\n?'
    return [regex]::Replace($Text, $pattern, "").TrimEnd()
}

Write-Host "JWPLC - activar piloto P2 compatible con Arduino IDE / sin compilar" -ForegroundColor Cyan
Write-Host ("PowerShell: {0} / {1}" -f $PSVersionTable.PSVersion, $PSVersionTable.PSEdition)
Write-Host ""

if (-not (Test-Path $ArchivePath))
{
    throw "No existe core precompilado Basic: $ArchivePath"
}
if (-not (Test-Path $StubPath))
{
    throw "No existe stub P2: $StubPath"
}
if (-not (Test-Path $PlatformLocalPath))
{
    throw "No existe platform.local.txt: $PlatformLocalPath"
}

$platformLocal = Get-Content -Path $PlatformLocalPath -Raw
if ($platformLocal -match 'recipe\.hooks\.core\.postbuild\.2')
{
    throw "platform.local.txt aun contiene el hook P2 antiguo. Ejecuta git pull antes de activar este piloto."
}
if ($platformLocal -notmatch 'build\.extra_libs')
{
    throw "platform.local.txt no documenta la estrategia P2 por build.extra_libs. Ejecuta git pull."
}

$archive = Get-Item $ArchivePath
if ($archive.Length -lt 1000000)
{
    throw ("El core precompilado parece demasiado pequeno: {0} bytes" -f $archive.Length)
}
$archiveHash = (Get-FileHash -Path $ArchivePath -Algorithm SHA256).Hash

$existing = ""
if (Test-Path $BoardsLocalPath)
{
    $existing = Get-Content -Path $BoardsLocalPath -Raw
}
$baseText = Remove-P2Block -Text $existing

$lines = New-Object System.Collections.Generic.List[string]
if (-not [string]::IsNullOrWhiteSpace($baseText))
{
    $lines.Add($baseText)
    $lines.Add("")
}
$lines.Add("# BEGIN JWPLC_P2_PRECOMPILED_CORE")
$lines.Add("# Generated by Activate-JWPLCP2IDECompatiblePilot.ps1. Pilot only; do not commit as final board definition.")
$lines.Add("jwplcbasic.build.core=jwcontrol_precompiled_stub")
$lines.Add('jwplcbasic.build.extra_libs="{runtime.platform.path}/precompiled/core/JWPLCBASIC/core.a"')
$lines.Add("# END JWPLC_P2_PRECOMPILED_CORE")
$lines | Out-File -FilePath $BoardsLocalPath -Encoding ascii

$written = Get-Content -Path $BoardsLocalPath -Raw
if ($written -notmatch '(?m)^jwplcbasic\.build\.core=jwcontrol_precompiled_stub\s*$')
{
    throw "No se pudo activar build.core=jwcontrol_precompiled_stub."
}
if ($written -notmatch '(?m)^jwplcbasic\.build\.extra_libs="\{runtime\.platform\.path\}/precompiled/core/JWPLCBASIC/core\.a"\s*$')
{
    throw "No se pudo activar build.extra_libs para el core P2."
}

Write-Host ("Archive Basic: {0} bytes" -f $archive.Length) -ForegroundColor Green
Write-Host ("SHA-256: {0}" -f $archiveHash) -ForegroundColor DarkGray
Write-Host ""
Write-Host "Overlay P2 IDE-compatible: ACTIVO" -ForegroundColor Green
Write-Host "  build.core       = jwcontrol_precompiled_stub"
Write-Host '  build.extra_libs = "{runtime.platform.path}/precompiled/core/JWPLCBASIC/core.a"'
Write-Host ""
Write-Host "=== P2 IDE-COMPATIBLE PILOT: ACTIVADO ===" -ForegroundColor Green
Write-Host "No se ejecuto ninguna compilacion."
Write-Host "Siguiente gate: cerrar/reabrir Arduino IDE y compilar/subir un sketch vacio sin borrar la cache global." -ForegroundColor Cyan
