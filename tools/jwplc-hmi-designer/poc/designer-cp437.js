  // tilde si existe (Á -> A), si no '?'. Saltos de línea -> espacio si
  // newlineAsSpace.
  function cppEscape(text, newlineAsSpace = false) {
    let out = '';
    for (const ch of String(text ?? '')) {
      let code = ch.codePointAt(0);
      if (newlineAsSpace && (code === 10 || code === 13)) code = 32;
      const k = glyphIndex(code);
      if (k === 0x5C) out += '\\\\';
      else if (k === 0x22) out += '\\"';
      else if (k >= 0x20 && k < 0x7F) out += String.fromCharCode(k);
      else out += '\\' + byteForGlyph(k).toString(8).padStart(3, '0');
    }
    return out;
  }

  return { glyphOf, glyphIndex, byteForGlyph, unsupported, cppEscape, LEGACY_SHIFT_FROM };
