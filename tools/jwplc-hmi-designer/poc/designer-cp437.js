  function glyphOf(code) {
    if (code >= 0 && code < 0x80) return code;
    const k = MAP.get(code);
    if (k === undefined || k === LEGACY_SHIFT_FROM) return -1;
    return k;
  }

  // Glifo que se dibuja: exacto, si no la letra sin tilde, si no '?'.
  function glyphIndex(code) {
    const k = glyphOf(code);
    if (k >= 0) return k;
    return FALLBACK.get(code) ?? QUESTION;
  }

  // Byte que hay que enviar a la TFT para ver el glifo k.
  function byteForGlyph(k) {
    return k > LEGACY_SHIFT_FROM ? k - 1 : k;
  }

  // Caracteres sin glifo (para avisar en el Designer).
  function unsupported(text) {
    const out = [];
    for (const ch of String(text ?? '')) {
      if (glyphOf(ch.codePointAt(0)) < 0 && !out.includes(ch)) out.push(ch);
    }
    return out;
  }

  // Contenido de un literal C++ (sin comillas) con los bytes de la TFT:
  // ASCII tal cual (\\ y \" escapados), el resto en octal de 3 dígitos (un
